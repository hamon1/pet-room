CREATE TABLE foods (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(50)   NOT NULL,
    type            VARCHAR(20)   NOT NULL,
    expiry_date     DATE          NOT NULL,
    opened_date     DATE,
    total_g         NUMERIC(9, 1),
    remaining_g     NUMERIC(9, 1),
    per_serving_g   NUMERIC(7, 1),
    times_per_day   INT,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_foods_owner_id ON foods (owner_id);

-- 여러 마리가 같은 먹이를 먹을 때 재고를 하나로 관리하기 위한 연결 테이블
CREATE TABLE food_pets (
    food_id BIGINT NOT NULL REFERENCES foods (id) ON DELETE CASCADE,
    pet_id  BIGINT NOT NULL REFERENCES pets (id) ON DELETE CASCADE,
    PRIMARY KEY (food_id, pet_id)
);

CREATE TABLE user_settings (
    user_id                BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    medical_notice_days    INT         NOT NULL,
    treatment_notice_days  INT         NOT NULL,
    expiry_notice_days     INT         NOT NULL,
    rebuy_notice_days      INT         NOT NULL,
    theme                  VARCHAR(20) NOT NULL,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);
