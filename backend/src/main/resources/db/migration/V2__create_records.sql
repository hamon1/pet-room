CREATE TABLE health_records (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id      BIGINT       NOT NULL REFERENCES pets (id) ON DELETE CASCADE,
    record_date DATE         NOT NULL,
    weight_kg   NUMERIC(6, 3),
    meal        VARCHAR(20),
    stool       VARCHAR(20),
    fed         VARCHAR(20),
    memo        VARCHAR(500),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_health_records_pet_date UNIQUE (pet_id, record_date)
);

CREATE TABLE medical_records (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id      BIGINT       NOT NULL REFERENCES pets (id) ON DELETE CASCADE,
    kind        VARCHAR(20)  NOT NULL,
    record_date DATE         NOT NULL,
    hospital    VARCHAR(50),
    content     VARCHAR(100) NOT NULL,
    next_date   DATE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_medical_records_pet_date ON medical_records (pet_id, record_date DESC);
-- 3단계 주요 이벤트 계산(다가오는 의료 일정)에서 사용
CREATE INDEX idx_medical_records_next_date ON medical_records (next_date) WHERE next_date IS NOT NULL;

CREATE TABLE special_records (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id      BIGINT       NOT NULL REFERENCES pets (id) ON DELETE CASCADE,
    item_key    VARCHAR(30)  NOT NULL,
    record_date DATE         NOT NULL,
    value       VARCHAR(100),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_special_records_pet_item_date ON special_records (pet_id, item_key, record_date DESC);

CREATE TABLE tank_fish (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id     BIGINT      NOT NULL REFERENCES pets (id) ON DELETE CASCADE,
    name       VARCHAR(30) NOT NULL,
    species    VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_tank_fish_pet_id ON tank_fish (pet_id);
